local E=...
Mock.event('ADDON_LOADED','Epicast');Mock.advance(0)
E.devMode=true;E.OpenOptions()
local p=E.panel
assert(p.tabs.central:GetText()=='Central set'and p.tabs.edge:GetText()=='Edge set')
assert(p.pages.central:IsVisible()and not p.pages.edge:IsVisible())
assert(p.sliders.gap and p.sliders.x.label:GetText()=='Horizontal position')
assert(not p.resource:IsVisible()and not p.meter.label:IsVisible())
assert(p.pages.central.spells:IsVisible()and not p.save.enabled)
local initial=E.Copy(EpicastDB)
p.right:Click();p.sliders.x:SetValue(120);p.sliders.gap:SetValue(620)
assert(E.editorSide=='right'and E.draft.sets.central.x==120 and E.HasChanges())
p.tabs.edge:Click()
assert(not p.pages.central:IsVisible()and p.pages.edge:IsVisible())
assert(E.editorSide=='left'and not p.sliders.gap)
assert(p.sliders.x.label:GetText()=='Inset from screen edges')
assert(p.resource:IsVisible()and p.meter.label:IsVisible()and not p.pages.edge.spells:IsVisible())
assert(p.active.edge:GetChecked()==false)
p.active.edge:Click();p.sliders.x:SetValue(80);p.sliders.y:SetValue(34)
p.resource:Click();Mock.menu[2].choose()
assert(E.GetSide(E.draft,'edge','left').resource=='mana')
assert(E.draft.sets.central.x==120 and E.draft.sets.central.gap==620)
assert(E.draft.sets.edge.x==80 and E.draft.sets.edge.y==34)
-- Merely selecting a tab keeps the draft and each tab's selected sister.
p.tabs.central:Click();assert(E.editorSide=='right'and p.sliders.x:GetValue()==120)
p.tabs.edge:Click();assert(E.editorSide=='left'and p.sliders.x:GetValue()==80)
assert(EpicastDB.sets.central.x==initial.sets.central.x and not EpicastDB.sets.edge.enabled)
-- A delayed menu callback is inert if combat starts or its page is no longer selected.
p.roles.edge:Click();assert(#Mock.menu==2);local chooseSpell=Mock.menu[1].choose
Mock.combat=true;chooseSpell();p.tabs.central:Click();assert(E.editorSet=='edge'and E.draft.sets.edge.role=='resources')
Mock.combat=false;p.tabs.central:Click();chooseSpell();assert(E.draft.sets.edge.role=='resources')
p.tabs.edge:Click();p.roles.edge:Click();Mock.menu[1].choose()
assert(E.draft.sets.edge.role=='spells'and E.draft.sets.central.role=='resources')
assert(not p.resource:IsVisible()and not p.meter.label:IsVisible()and p.pages.edge.spells:IsVisible())
assert(E.draft.sets.edge.x==80 and E.draft.sets.central.gap==620)
-- Manual effects stop on selection changes, including clicks on the artwork.
assert(E.TestBoundEffect('left','arcaneTome',4))
local effect=E.instances.edge.left.addedEffectSlots[4]
assert(effect.boundTest);p.right:Click();assert(not effect.boundTest)
p.left:Click();assert(E.TestBoundEffect('left','arcaneTome',4));p.tabs.central:Click();assert(not effect.boundTest)
E.instances.edge.right.handle:emit('OnMouseDown')
assert(E.editorSet=='edge'and E.editorSide=='right'and p.pages.edge:IsVisible())
assert(p.subject:GetText():find('Arcane Scroll',1,true))
-- Save commits both pages; Cancel restores both pages and role/content tuning.
p.save:Click();assert(not E.HasChanges()and not p.save.enabled)
assert(EpicastDB.sets.central.x==120 and EpicastDB.sets.edge.x==80 and EpicastDB.sets.edge.role=='spells')
p.sliders.x:SetValue(150);p.tabs.central:Click();p.sliders.y:SetValue(90);p.swapRoles:Click()
p.cancel:Click();assert(not p:IsShown()and E.draft==nil)
E.OpenOptions();assert(E.draft.sets.edge.x==80 and E.draft.sets.central.y==0 and E.draft.sets.edge.role=='spells')
p.tabs.edge:Click();p.reset:Click()
assert(E.draft.sets.edge.x==0 and E.draft.sets.edge.y==0 and E.draft.sets.central.x==120)
p:Hide()
print('PASS: distinct Central/Edge pages, contextual controls, remembered sisters, role menus, combat guards, test cancellation and shared Save/Cancel')
