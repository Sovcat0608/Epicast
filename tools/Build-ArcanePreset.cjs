// Builds only from the approved effect-only export; never reads game settings.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const source=JSON.parse(fs.readFileSync(path.join(root,'tests/fixtures/arcane-beta13.json'),'utf8'));
const allowed=new Set(JSON.parse(fs.readFileSync(path.join(root,'tools/forever-effects.json'),'utf8')).allowed);
if(source.length!==12||source.some(r=>!allowed.has(r.fileID)))throw Error('Invalid approved Arcane preset');
function literal(v,depth=0){
 if(v===null)return'nil';
 if(typeof v==='boolean')return String(v);
 if(typeof v==='number'){if(!Number.isFinite(v))throw Error('Non-finite value');return String(v);}
 if(typeof v==='string')return JSON.stringify(v);
 const entries=Array.isArray(v)?v.map((x,i)=>[i+1,x]):Object.entries(v).sort(([a],[b])=>a.localeCompare(b));
 const pad=' '.repeat(depth+1),end=' '.repeat(depth);
 return'{\n'+entries.map(([k,x])=>pad+'['+literal(k)+']='+literal(x,depth+1)+',').join('\n')+'\n'+end+'}';
}
const output='local _,E=...\n-- Approved Arcane effects and bindings, 2026-11-16. Placement is per player.\n-- Generated by tools/Build-ArcanePreset.cjs from the effect-only fixture.\nE.AddedEffectDefaults.mageArcane='+literal(source)+'\n';
fs.writeFileSync(path.join(root,'ArcanePreset.lua'),output);
console.log('Built 12 approved Arcane layers; no artwork or player placement changes');
