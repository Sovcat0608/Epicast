// Build a self-contained spell/particle catalog; no game binaries are shipped.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const sourceDir=process.argv[2]||path.join(root,'artifacts/catalog-source');
const metadata=JSON.parse(fs.readFileSync(path.join(sourceDir,'source.json'),'utf8').replace(/^\uFEFF/,''));
const presets=JSON.parse(fs.readFileSync(path.join(__dirname,'effect-preview-presets.json'),'utf8'));
const entries=new Map(),inputs={};
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
for(const part of ['spells','misc']){
 const bytes=fs.readFileSync(path.join(sourceDir,part+'.csv'));inputs[part+'.csv']={bytes:bytes.length,sha256:hash(bytes)};
 for(const line of bytes.toString('utf8').split(/\r?\n/)){
  const match=/^(\d+);((?:spells|particles)\/[^\r\n]*\.m2)$/i.exec(line);
  if(!match)continue;
  const id=Number(match[1]),file=match[2].toLowerCase();
  if(!Number.isInteger(id)||id<1||id>0xffffffff)throw Error('Invalid catalog ID');
  if(entries.has(id)&&entries.get(id)!==file)throw Error('Conflicting file ID '+id);
  entries.set(id,file);
 }
}
const knownCount=entries.size;
for(const[id,preset]of Object.entries(presets))if(!entries.has(Number(id)))entries.set(Number(id),preset.path);
if(knownCount<9000)throw Error('Incomplete spell/particle source');
const availabilityBytes=fs.readFileSync(path.join(__dirname,'forever-effects.json'));
const availability=JSON.parse(availabilityBytes),allIDs=[...availability.allowed,...Object.values(availability.rejected).flat()];
if(availability.product!=='wowf'||availability.sourceModels!==entries.size||new Set(allIDs).size!==entries.size||allIDs.some(id=>!entries.has(id)))throw Error('Forever inspection does not match source catalog');
const allowed=new Set(availability.allowed),sourceCount=entries.size;
for(const id of entries.keys())if(!allowed.has(id))entries.delete(id);
const quote=s=>JSON.stringify(s);
const lines=['-- Generated by tools/Build-EffectCatalog.cjs from the wowdev community listfile.',
 `-- Source revision: ${metadata.Revision}`,'local _,E=...','E.EffectLibrary=E.EffectLibrary or {}','local Viewer=E.EffectLibrary',
 `Viewer.catalogCount=${entries.size}`,`Viewer.catalogBuild=${quote(availability.version)}`,'Viewer.presets={'];
for(const[id,preset]of Object.entries(presets)){
 if(!allowed.has(Number(id)))continue;
 const fields=[];
 for(const[key,v]of Object.entries(preset))if(key!=='path')fields.push(`${key}=${Array.isArray(v)?'{'+v.join(',')+'}':typeof v==='string'?quote(v):v}`);
 lines.push(` [${id}]={${fields.join(',')}},`);
}
lines.push('}','Viewer.catalog=[=[');
for(const[id,file]of [...entries].sort((a,b)=>a[0]-b[0])){
 if(!file.endsWith('.m2')||/[\r\n\x00;]/.test(file)||file.includes(']=]')||file.split('/').includes('..'))throw Error('Invalid model path: '+file);
 lines.push(`${id};${file}`);
}
lines.push(']=]','');const output=lines.join('\n');
fs.writeFileSync(path.join(root,'EffectCatalog.lua'),output);
const manifest={repository:metadata.Repository,revision:metadata.Revision,sourceDate:metadata.Date,inputs,sourceModels:sourceCount,foreverBuild:availability.version,foreverRoot:availability.rootKey,availabilitySHA256:hash(availabilityBytes),previewPresets:Object.keys(presets).filter(id=>allowed.has(Number(id))).length,models:entries.size,catalogSHA256:hash(output)};
fs.writeFileSync(path.join(__dirname,'effect-catalog-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(`Catalog: ${entries.size} Forever models from ${sourceCount} candidates, ${manifest.previewPresets} preview presets`);
