// Bake from the unsharpened, registered source cels using the same sampler
// and alpha-protected CAS implementation as the size-specific static crests.
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { buildSize } = require('./artwork/Build-SkycutterSizes.cjs');
const { sharpen, sharpness, blend } = require('./artwork/Build-SkycutterCAS.cjs');

const root = path.resolve(__dirname, '..');
const capture = path.resolve(process.argv[2]);
const source = JSON.parse(fs.readFileSync(path.join(capture, 'registration.json'), 'utf8'));
const [sourceWidth, sourceHeight] = source.source_size;
const widths = [192, 288, 384, 480, 576, 660];
const backings = [256, 512, 1024];
const hash = pixels => createHash('sha256').update(pixels).digest('hex');

function layout(width, height, total) {
    const options = [];
    for (const tw of backings) for (const th of backings) {
        if (tw < width || th < height) continue;
        const columns = Math.floor(tw / width);
        const perPage = columns * Math.floor(th / height);
        const count = Math.ceil(total / perPage);
        options.push({ tw, th, columns, perPage, count, area: count * tw * th });
    }
    return options.sort((a, b) => a.area - b.area || a.count - b.count)[0];
}

function header(width, height) {
    const data = Buffer.alloc(18);
    data[2] = 2;
    data[16] = 32;
    data[17] = 40;
    data.writeUInt16LE(width, 12);
    data.writeUInt16LE(height, 14);
    return data;
}

function sampleCel(index, width, height) {
    const filename = `registered-${String(index).padStart(2, '0')}.bgra`;
    const pixels = fs.readFileSync(path.join(capture, filename));
    const base = buildSize(pixels, sourceWidth, sourceHeight, width, height);
    const cas = sharpen(base, width, height);
    for (let offset = 21; offset < base.length; offset += 4) {
        if (cas[offset] !== base[offset]) throw Error('CAS altered source alpha');
    }
    return cas;
}

function pack(width, media) {
    const height = width * 4 / 3;
    const bank = layout(width, height, source.frame_count);
    const { tw, th, columns, perPage, count } = bank;
    // Reuse the former 384-pixel bank filenames for an in-place upgrade.
    const stem = width === 384 ? 'RestorationIdle' : `RestorationIdleCASSize${width}Page`;
    const frames = new Set();
    for (let page = 0; page < count; page += 1) {
        const canvas = Buffer.alloc(tw * th * 4);
        const pageFrames = Math.min(perPage, source.frame_count - page * perPage);
        for (let cell = 0; cell < pageFrames; cell += 1) {
            const cel = sampleCel(page * perPage + cell, width, height);
            const stride = cel.readUInt16LE(12);
            const x = (cell % columns) * width;
            const y = Math.floor(cell / columns) * height;
            const digest = createHash('sha256');
            for (let row = 0; row < height; row += 1) {
                const start = 18 + row * stride * 4;
                const line = cel.subarray(start, start + width * 4);
                line.copy(canvas, ((y + row) * tw + x) * 4);
                digest.update(line);
            }
            frames.add(digest.digest('hex'));
        }
        const name = `Media/${stem}${String(page + 1).padStart(2, '0')}.tga`;
        const payload = Buffer.concat([header(tw, th), canvas]);
        fs.writeFileSync(path.join(root, name), payload);
        media[name] = { bytes: payload.length, sha256: hash(payload) };
    }
    if (frames.size !== source.frame_count) throw Error(`Repeated frames in size ${width}`);
    console.log(`${width} × ${height}: ${frames.size} Lanczos2 + CAS poses in ${count} atlas pages`);
    return { width, height, stem, tw, th, columns, perPage, count };
}

if (source.frame_count !== 32 || source.preview.fps !== 8 || source.preview.period !== 4000) {
    throw Error('Unexpected idle cadence');
}
const manifestPath = path.join(root, 'tools/media-manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const banks = widths.map(width => pack(width, manifest));
const data = banks.map(({ width, height, stem, tw, th, columns, perPage, count }) =>
    `    [${width}] = { stem = "${stem}", width = ${width / tw}, height = ${height / th}, columns = ${columns}, perPage = ${perPage}, count = ${count} },`
).join('\n');
fs.writeFileSync(path.join(root, 'RestorationIdleData.lua'),
    `-- Generated by tools/Build-RestorationIdle.cjs.\nlocal _, E = ...\nE.RestorationIdleBanks = {\n${data}\n}\n`);
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(capture, 'bake.json'),
    JSON.stringify({ ...source, lanczos: 2, cas: { sharpness, blend }, banks }, null, 2) + '\n');
